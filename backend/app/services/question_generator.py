"""
Question Generation Service for AdaptiveLearn AI.
Integrates Google Gemini (gemini-1.5-flash) to dynamically synthesize
personalized multiple-choice questions targeting student learning gaps.

Features:
- Learning gap-aware prompt formulation
- Resilient Gemini API integration (HTTP / google-genai)
- Multi-step validation pipeline:
    1. Schema & JSON structure validation
    2. Exactly 4 distinct options (A, B, C, D)
    3. Correct answer key validity
    4. Duplicate question and option text detection
    5. Difficulty calibration and pedagogical explanation checks
- Automatic database persistence with provenance tracking
- Seamless graceful fallback to verified curated question bank
"""

import json
import logging
from typing import List, Optional, Dict, Any, Tuple
from sqlalchemy.orm import Session
import httpx

from app.core.config import settings
from app.models.models import Question, Concept

logger = logging.getLogger(__name__)


class QuestionValidationPipeline:
    """Validates candidate questions generated by AI before allowing them into the system."""

    @staticmethod
    def validate_candidate(candidate: Dict[str, Any], existing_texts: List[str]) -> Tuple[bool, Optional[str]]:
        # 1. Check required fields
        required_fields = ["question_text", "options", "correct_option", "explanation"]
        for field in required_fields:
            if not candidate.get(field):
                return False, f"Missing or empty required field: {field}"

        question_text = str(candidate["question_text"]).strip()
        if len(question_text) < 15:
            return False, "Question text is too short to be pedagogically valid"

        # 2. Check for duplicate questions in current concept
        norm_q = question_text.lower()
        for existing in existing_texts:
            if norm_q == existing.strip().lower() or (len(norm_q) > 20 and norm_q in existing.strip().lower()):
                return False, "Duplicate question text detected"

        # 3. Check options: must be list of exactly 4
        options = candidate.get("options")
        if not isinstance(options, list) or len(options) != 4:
            return False, f"Question must have exactly 4 options, got {len(options) if isinstance(options, list) else 0}"

        seen_ids = set()
        seen_texts = set()
        for opt in options:
            if not isinstance(opt, dict) or "id" not in opt or "text" not in opt:
                return False, "Option items must be objects with 'id' and 'text'"
            opt_id = str(opt["id"]).strip().upper()
            opt_text = str(opt["text"]).strip()

            if opt_id not in ["A", "B", "C", "D"]:
                return False, f"Invalid option identifier: {opt_id}. Must be A, B, C, or D"
            if not opt_text:
                return False, f"Empty text for option {opt_id}"

            if opt_id in seen_ids:
                return False, f"Duplicate option identifier: {opt_id}"
            if opt_text.lower() in seen_texts:
                return False, f"Duplicate option text across choices: {opt_text}"

            seen_ids.add(opt_id)
            seen_texts.add(opt_text.lower())

        if seen_ids != {"A", "B", "C", "D"}:
            return False, f"Options must contain all of A, B, C, D; got {seen_ids}"

        # 4. Correct option must match one of A, B, C, D
        correct_opt = str(candidate.get("correct_option", "")).strip().upper()
        if correct_opt not in ["A", "B", "C", "D"]:
            return False, f"Correct option '{correct_opt}' does not match valid options A, B, C, D"

        # 5. Explanation check
        explanation = str(candidate.get("explanation", "")).strip()
        if len(explanation) < 15:
            return False, "Pedagogical explanation is insufficient or missing"

        return True, None


class QuestionGenerationService:
    def __init__(self):
        self.validator = QuestionValidationPipeline()

    @property
    def is_available(self) -> bool:
        """Determines if the Gemini AI generation service is configured and ready."""
        return bool(settings.GEMINI_API_KEY and settings.AI_PROVIDER.lower() == "gemini")

    def generate_questions_for_gap(
        self,
        db: Session,
        concept: Concept,
        target_difficulty: int = 1,
        gap_reason: Optional[str] = None,
        count: int = 1
    ) -> List[Question]:
        """
        Generates targeted questions addressing a student's diagnosed learning gap.
        Persists validated questions to the database and returns the Question ORM objects.
        If unavailable or if validation fails, returns an empty list (allowing caller to use curated bank).
        """
        if not self.is_available:
            logger.info("Gemini AI provider not configured. Skipping generation.")
            return []

        # Retrieve existing questions for duplicate prevention
        existing = db.query(Question.question_text).filter(Question.concept_id == concept.id).all()
        existing_texts = [row[0] for row in existing]

        difficulty_labels = {1: "Easy (Foundational/Conceptual)", 2: "Medium (Application)", 3: "Hard (Analysis/Advanced)"}
        difficulty_name = difficulty_labels.get(target_difficulty, "Medium")

        gap_context = ""
        if gap_reason:
            gap_context = f"\nSpecific Student Learning Gap: {gap_reason}\nDesign questions specifically diagnosing and clarifying this misconception.\n"

        prompt = f"""You are an expert curriculum author and adaptive learning educator.
Generate {count} multiple choice questions (MCQ) for students on the curriculum concept:
Concept: {concept.name}
Description: {concept.description or 'Foundational curriculum concept'}
Learning Objective: {concept.learning_objective or 'Mastery of fundamental principles'}
Target Difficulty: {target_difficulty} - {difficulty_name}
{gap_context}
Strict Requirements:
1. Exactly 4 distinct options per question labeled A, B, C, D.
2. Only one unequivocally correct answer based on educational standards.
3. Realistic, plausible distractors reflecting common student misconceptions.
4. Clear, pedagogical explanation justifying why the correct answer is right and why distractors are misconceptions.
5. Return ONLY a valid JSON array of objects conforming to this schema without Markdown ticks or commentary:
[
  {{
    "question_text": "Clear, concise question statement",
    "options": [
      {{"id": "A", "text": "First choice"}},
      {{"id": "B", "text": "Second choice"}},
      {{"id": "C", "text": "Third choice"}},
      {{"id": "D", "text": "Fourth choice"}}
    ],
    "correct_option": "A",
    "explanation": "Clear explanation of the concept and why other options are incorrect.",
    "difficulty": {target_difficulty}
  }}
]
"""
        try:
            url = f"https://generativelanguage.googleapis.com/v1beta/models/{settings.GEMINI_MODEL}:generateContent?key={settings.GEMINI_API_KEY}"
            payload = {
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {
                    "response_mime_type": "application/json",
                    "temperature": 0.4
                }
            }

            with httpx.Client(timeout=15.0) as client:
                res = client.post(url, json=payload)
                if res.status_code != 200:
                    logger.warning(f"Gemini API returned status {res.status_code}: {res.text[:200]}")
                    return []

                data = res.json()
                raw_text = data["candidates"][0]["content"]["parts"][0]["text"].strip()

                if raw_text.startswith("```json"):
                    raw_text = raw_text[7:]
                if raw_text.startswith("```"):
                    raw_text = raw_text[3:]
                if raw_text.endswith("```"):
                    raw_text = raw_text[:-3]

                items = json.loads(raw_text.strip())
                if isinstance(items, dict):
                    items = [items]

                saved_questions: List[Question] = []
                for item in items:
                    is_valid, error_msg = self.validator.validate_candidate(item, existing_texts)
                    if not is_valid:
                        logger.warning(f"Rejected candidate question from Gemini: {error_msg}")
                        continue

                    # Create and persist question
                    new_q = Question(
                        concept_id=concept.id,
                        question_text=item["question_text"].strip(),
                        options=[{"id": o["id"].upper(), "text": o["text"].strip()} for o in item["options"]],
                        correct_option=item["correct_option"].strip().upper(),
                        explanation=item["explanation"].strip(),
                        difficulty=int(item.get("difficulty", target_difficulty)),
                        source_reference=f"Gemini AI ({settings.GEMINI_MODEL})",
                        is_verified=True,
                        is_active=True
                    )
                    db.add(new_q)
                    db.flush()
                    saved_questions.append(new_q)
                    existing_texts.append(new_q.question_text)

                if saved_questions:
                    db.commit()
                    logger.info(f"Successfully generated and persisted {len(saved_questions)} questions via Gemini for '{concept.name}'")

                return saved_questions

        except Exception as e:
            logger.warning(f"Question generation via Gemini failed or timed out: {e}. Falling back to question bank.")
            db.rollback()
            return []


question_generator = QuestionGenerationService()
